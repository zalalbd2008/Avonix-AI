const cache = new Map<PlatformLocale, MessageTable>();

/** Resolved UI messages for a locale (English fallback for missing keys). */
export function getPlatformMessages(locale: PlatformLocale): MessageTable {
  const cached = cache.get(locale);
  if (cached) return cached;

  const pack = PACKS[locale];
  const merged = { ...EN, ...pack } as MessageTable;
  cache.set(locale, merged);
  return merged;
}

export function translate(
  locale: PlatformLocale,
  key: MessageKey,
): string {
  return getPlatformMessages(locale)[key];
}
